"""Generate the tap formula from verified, published fmn release archives."""

import argparse
import hashlib
import re
from pathlib import Path


STABLE_TAG = re.compile(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)")
PLATFORMS = (
    ("macos", (("arm", "aarch64-apple-darwin"), ("intel", "x86_64-apple-darwin"))),
    ("linux", (("arm", "aarch64-unknown-linux-musl"), ("intel", "x86_64-unknown-linux-musl"))),
)


def stable_version(tag):
    if not STABLE_TAG.fullmatch(tag):
        raise ValueError("Homebrew requires a stable vMAJOR.MINOR.PATCH release tag")
    return tag[1:]


def validate_release(tag, release, latest):
    if release["tagName"] != tag or release["isDraft"]:
        raise ValueError("Homebrew requires a published release matching the requested tag")
    if release["isPrerelease"]:
        return False
    stable_version(tag)
    if tag != latest:
        raise ValueError(f"Refusing to replace the tap with a release other than {latest}")
    return True


def homebrew_formula(tag, directory):
    version = stable_version(tag)
    checksums = {}
    for line in (directory / "sha256.sum").read_text().splitlines():
        digest, filename = line.split()
        filename = filename.removeprefix("*")
        if filename in checksums:
            raise ValueError(f"Duplicate checksum for {filename}")
        checksums[filename] = digest

    platforms = []
    for system, targets in PLATFORMS:
        architectures = []
        for arch, target in targets:
            filename = f"fmn-{target}.tar.xz"
            digest = hashlib.sha256((directory / filename).read_bytes()).hexdigest()
            if checksums.get(filename) != digest:
                raise ValueError(f"Missing or mismatched checksum for {filename}")
            architectures.append(f'''    on_{arch} do
      url "https://github.com/z0mbix/fmn/releases/download/{tag}/{filename}"
      sha256 "{digest}"
    end''')
        platforms.append(f"  on_{system} do\n" + "\n\n".join(architectures) + "\n  end")

    platform_blocks = "\n\n".join(platforms)
    return f'''# Generated by z0mbix/fmn scripts/homebrew_formula.py.
class Fmn < Formula
  desc "Local-first shell history manager for Fish, Zsh, and Bash"
  homepage "https://github.com/z0mbix/fmn"
  version "{version}"
  license "MIT"

{platform_blocks}

  def install
    bin.install "fmn"
    doc.install "README.md"
  end

  test do
    assert_equal "fmn {version}", shell_output("#{{bin}}/fmn --version").strip
    ENV["FMN_DATA_DIR"] = (testpath/"history").to_s
    ENV["FMN_CONFIG"] = (testpath/"config.toml").to_s
    system bin/"fmn", "doctor"
  end
end
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag")
    parser.add_argument("release_directory", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    formula = homebrew_formula(args.tag, args.release_directory)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(formula)


if __name__ == "__main__":
    main()
